<#
  Publish the 10km crop-diversity grid (03 folder) to GeoServer so the
  planting-analysis module can offer a "grid view" next to the parcel view.

  Usage:
    powershell -ExecutionPolicy Bypass -File .\publish-grid.ps1

  Options:
    -Server    http://10.98.59.222:8080      GeoServer base URL
    -User      admin                         admin account
    -Password  geoserver                     admin password
    -Workspace agri-agent                    target workspace
    -SourceDir C:\Users\27814\Desktop\new\new\03   folder holding the grid shapefile
    -StyleFile .\grid-diversity-10.sld       SLD (generated by scripts/grid-diversity.cjs)

  Published layer: agri-agent:bh_crop_grid (coloured by N_CROP, crop types per cell)
  Idempotent: re-running replaces the datastore / layer / style.
#>

param(
    [string]$Server    = 'http://10.98.59.222:8080',
    [string]$User      = 'admin',
    [string]$Password  = 'geoserver',
    [string]$Workspace = 'agri-agent',
    [string]$SourceDir = 'C:\Users\27814\Desktop\new\new\03',
    [string]$Store     = 'grid_diversity',
    [string]$Layer     = 'bh_crop_grid',
    [string]$StyleFile = (Join-Path $PSScriptRoot 'grid-diversity-10.sld'),
    [string]$StyleName = 'grid-diversity-10'
)

$ErrorActionPreference = 'Stop'
$rest = "$Server/geoserver/rest"
$auth = @{ Authorization = 'Basic ' + [Convert]::ToBase64String(
    [Text.Encoding]::ASCII.GetBytes("${User}:${Password}")) }

function Invoke-GeoServerRest {
    param(
        [Parameter(Mandatory = $true)][string]$Method,
        [Parameter(Mandatory = $true)][string]$Uri,
        [string]$ContentType,
        $Body,
        [switch]$AllowMissing
    )
    $req = @{ Method = $Method; Uri = $Uri; Headers = $auth; TimeoutSec = 600 }
    if ($ContentType) { $req['ContentType'] = $ContentType }
    if ($null -ne $Body) { $req['Body'] = $Body }
    try {
        return Invoke-RestMethod @req
    } catch {
        if ($AllowMissing) { return $null }
        throw
    }
}

Write-Host "==> checking workspace $Workspace"
$ws = Invoke-GeoServerRest -Method Get -Uri "$rest/workspaces/$Workspace" -ContentType 'application/json' -AllowMissing
if (-not $ws) {
    Write-Host "    workspace missing, creating it"
    Invoke-GeoServerRest -Method Post -Uri "$rest/workspaces" -ContentType 'application/json' `
        -Body (@{ workspace = @{ name = $Workspace } } | ConvertTo-Json -Depth 5) | Out-Null
} else {
    Write-Host "    ok"
}

# The source shapefile may be renamed between data versions, but the published
# feature type would keep pointing at the OLD file. Drop the layer and every
# feature type in the store first, so the new upload is what gets published.
Write-Host "==> resetting old layer and feature types"
Invoke-GeoServerRest -Method Delete -Uri "$rest/layers/${Workspace}:${Layer}?recurse=true" `
    -ContentType 'application/json' -AllowMissing | Out-Null
$oldTypes = Invoke-GeoServerRest -Method Get -Uri "$rest/workspaces/$Workspace/datastores/$Store/featuretypes.json" `
    -ContentType 'application/json' -AllowMissing
if ($oldTypes) {
    foreach ($ft in $oldTypes.featureTypes.featureType) {
        Invoke-GeoServerRest -Method Delete -Uri "$rest/workspaces/$Workspace/datastores/$Store/featuretypes/$($ft.name)?recurse=true" `
            -ContentType 'application/json' -AllowMissing | Out-Null
    }
}

if (-not (Test-Path -LiteralPath $SourceDir)) { throw "source folder not found: $SourceDir" }
$shp = Get-ChildItem -LiteralPath $SourceDir -Filter '*.shp' | Select-Object -First 1
if (-not $shp) { throw "no .shp found in $SourceDir" }
$native = [IO.Path]::GetFileNameWithoutExtension($shp.Name)

Write-Host "==> zipping $($shp.Name)"
$zip = Join-Path $env:TEMP 'grid_diversity.zip'
if (Test-Path -LiteralPath $zip) { Remove-Item -LiteralPath $zip -Force }
$parts = Get-ChildItem -LiteralPath $SourceDir -Filter "$native.*" | ForEach-Object { $_.FullName }
Compress-Archive -Path $parts -DestinationPath $zip -Force

Write-Host "==> uploading datastore $Store"
Invoke-GeoServerRest -Method Put -Uri "$rest/workspaces/$Workspace/datastores/$Store/file.shp" `
    -ContentType 'application/zip' -Body ([IO.File]::ReadAllBytes($zip)) | Out-Null
Remove-Item -LiteralPath $zip -Force

Write-Host "==> publishing layer $Layer"
# Do NOT force srs here: the grid .prj is a custom Albers projection, so let
# GeoServer read it from the file. Declaring EPSG:4326 would make it treat
# metre coordinates as degrees and the layer renders as a solid block.
Invoke-GeoServerRest -Method Post -Uri "$rest/workspaces/$Workspace/datastores/$Store/featuretypes" `
    -ContentType 'application/json' -AllowMissing `
    -Body (@{ featureType = @{ name = $Layer; nativeName = $native } } | ConvertTo-Json -Depth 5) | Out-Null

Write-Host "==> uploading style $StyleName"
if (-not (Test-Path -LiteralPath $StyleFile)) { throw "SLD not found: $StyleFile" }
$styleBody = [Text.Encoding]::UTF8.GetBytes((Get-Content -LiteralPath $StyleFile -Raw -Encoding UTF8))
# Try an update first; GeoServer answers 500 for a GET on an existing style,
# so skip the existence probe: fall back to POST when PUT fails.
try {
    Invoke-GeoServerRest -Method Put -Uri "$rest/workspaces/$Workspace/styles/$StyleName" `
        -ContentType 'application/vnd.ogc.sld+xml; charset=UTF-8' -Body $styleBody | Out-Null
} catch {
    Write-Host "    style not found, creating it"
    Invoke-GeoServerRest -Method Post -Uri "$rest/workspaces/$Workspace/styles?name=$StyleName" `
        -ContentType 'application/vnd.ogc.sld+xml; charset=UTF-8' -Body $styleBody | Out-Null
}

Write-Host "==> applying $StyleName to $Layer"
$body = @{ layer = @{ defaultStyle = @{ name = $StyleName; workspace = $Workspace } } } | ConvertTo-Json -Depth 5
Invoke-GeoServerRest -Method Put -Uri "$rest/layers/${Workspace}:$Layer" -ContentType 'application/json' -Body $body | Out-Null

Write-Host ""
Write-Host "Done. Verify:"
Write-Host "  $Server/geoserver/$Workspace/wms?service=WMS&version=1.1.1&request=GetCapabilities"
